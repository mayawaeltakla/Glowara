class DuaScreen extends StatefulWidget {
  const DuaScreen({super.key});

  @override
  State<DuaScreen> createState() => _DuaScreenState();
}

class _DuaScreenState extends State<DuaScreen> {
  bool _loaded = false;
  String _query = '';
  Set<int> _done = <int>{};
  final Map<int, int> _counts = <int, int>{};

  /// يتجدد كل يوم لأن المفتاح يحمل تاريخ اليوم.
  String get _key => 'dua_done_${dateKey(DateTime.now())}';
  String get _countsKey => 'dua_counts_${dateKey(DateTime.now())}';

  @override
  void didChangeDependencies() {
    super.didChangeDependencies();
    if (!_loaded) {
      _loaded = true;
      _load();
    }
  }

  Future<void> _load() async {
    final settings = AppState.of(context).settings;
    final raw = await settings.get<String>(_key);
    final rawCounts = await settings.get<String>(_countsKey);
    if (!mounted) return;
    setState(() {
      if (raw != null && raw.isNotEmpty) {
        _done = raw.split(',').map(int.tryParse).whereType<int>().toSet();
      }
      if (rawCounts != null && rawCounts.isNotEmpty) {
        for (final part in rawCounts.split(',')) {
          final kv = part.split(':');
          if (kv.length != 2) continue;
          final k = int.tryParse(kv[0]);
          final v = int.tryParse(kv[1]);
          if (k != null && v != null) _counts[k] = v;
        }
      }
    });
  }

  Future<void> _toggle(int i) async {
    final times = kDuas[i].times;
    setState(() {
      if (times <= 1) {
        _done.contains(i) ? _done.remove(i) : _done.add(i);
      } else {
        final next = (_counts[i] ?? 0) + 1;
        if (next > times) {
          _counts.remove(i);
          _done.remove(i);
        } else {
          _counts[i] = next;
          if (next >= times) _done.add(i);
        }
      }
    });
    final settings = AppState.of(context).settings;
    final list = _done.toList()..sort();
    await settings.set(_key, list.join(','));
    await settings.set(_countsKey, _counts.entries.map((e) => '${e.key}:${e.value}').join(','));
  }

  @override
  Widget build(BuildContext context) {
    final c = context.glowColors;
    final total = kDuas.length;
    final q = _query.trim();
    // فهارس الأدعية المطابقة للبحث (نحتفظ بالفهرس الأصلي لأن الحالة محفوظة به).
    final visible = <int>[
      for (var k = 0; k < total; k++)
        if (q.isEmpty || kDuas[k].text.contains(q) || (kDuas[k].intro ?? '').contains(q)) k,
    ];
    return GlowPage(
      title: 'الدعاء',
      child: ListView.builder(
        padding: const EdgeInsets.only(bottom: 24),
        itemCount: visible.length + 1,
        itemBuilder: (context, index) {
          if (index == 0) {
            return Padding(
              padding: const EdgeInsets.only(bottom: 12),
              child: GlowCard(
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: <Widget>[
                    Row(
                      children: <Widget>[
                        Expanded(
                          child: Text(
                            _done.length >= total
                                ? 'أتممتِ أدعية اليوم، تقبّل الله منك'
                                : 'ضعي علامة على كل دعاء بعد قراءته',
                            style: TextStyle(fontWeight: FontWeight.w700, color: c.onSurface),
                          ),
                        ),
                        Text('${_done.length}/$total',
                            style: TextStyle(fontWeight: FontWeight.w700, color: c.primary)),
                      ],
                    ),
                    const SizedBox(height: 8),
                    GlowProgress(value: total == 0 ? 0 : _done.length / total),
                    const SizedBox(height: 6),
                    Text(
                      'تُمسح العلامات تلقائيًا كل يوم لتقرئيها من جديد.',
                      style: TextStyle(fontSize: 11.5, color: c.onSurfaceVariant),
                    ),
                    const SizedBox(height: 10),
                    TextField(
                      onChanged: (v) => setState(() => _query = v),
                      decoration: const InputDecoration(
                        hintText: 'ابحثي في الأدعية',
                        prefixIcon: Icon(Icons.search),
                        isDense: true,
                      ),
                    ),
                  ],
                ),
              ),
            );
          }
          final i = visible[index - 1];
          final dua = kDuas[i];
          final done = _done.contains(i);
          return Padding(
            padding: const EdgeInsets.only(bottom: 10),
            child: GlowCard(
              color: done ? c.primaryContainer : null,
              child: Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: <Widget>[
                  if (dua.intro != null)
                    Padding(
                      padding: const EdgeInsets.only(bottom: 6),
                      child: Text(
                        dua.intro!,
                        style: TextStyle(fontSize: 12, fontWeight: FontWeight.w700, color: c.primary),
                      ),
                    ),
                  Text(
                    dua.text,
                    textDirection: TextDirection.rtl,
                    style: TextStyle(fontSize: 17, height: 2, color: c.onSurface),
                  ),
                  if (dua.note != null)
                    Padding(
                      padding: const EdgeInsets.only(top: 4),
                      child: Text(
                        dua.note!,
                        style: TextStyle(fontSize: 12, height: 1.6, color: c.primary),
                      ),
                    ),
                  const SizedBox(height: 4),
                  Row(
                    children: <Widget>[
                      IconButton(
                        tooltip: 'نسخ',
                        icon: Icon(Icons.copy_rounded, size: 20, color: c.onSurfaceVariant),
                        onPressed: () async {
                          await Clipboard.setData(ClipboardData(text: dua.text));
                          if (!context.mounted) return;
                          ScaffoldMessenger.of(context).showSnackBar(
                            const SnackBar(content: Text('تم النسخ')),
                          );
                        },
                      ),
                      const Spacer(),
                      FilledButton.tonalIcon(
                        onPressed: () => _toggle(i),
                        icon: Icon(done ? Icons.check_circle : Icons.radio_button_unchecked),
                        label: Text(
                          dua.times <= 1
                              ? (done ? 'قرأته' : 'علّمي كمقروء')
                              : (done
                                  ? 'تمّت ${dua.times}/${dua.times}'
                                  : 'اضغطي عند كل مرة ${_counts[i] ?? 0}/${dua.times}'),
                        ),
                      ),
                    ],
                  ),
                ],
              ),
            ),
          );
        },
      ),
    );
  }
}
